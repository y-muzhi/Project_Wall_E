HEADING = re.compile(r'^#{1,2} (\d+(?:\.\d+)?)(?:\.)? |^# (附录A)\.', re.MULTILINE)


def sections(source):
    headings = list(HEADING.finditer(source))
    return {
        match.group(1) or match.group(2): source[
            match.start() : headings[index + 1].start() if index + 1 < len(headings) else None
        ].strip()
        for index, match in enumerate(headings)
    }


def revise(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f'Shared template wording changed near {old[:45]}')
    return text.replace(old, new, 1)


def remove_lines(text, *prefixes):
    return '\n'.join(line for line in text.splitlines() if not line.startswith(prefixes))


