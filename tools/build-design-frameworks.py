def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, help='Write candidates into a new directory')
    args = parser.parse_args()
    source = sections(SOURCE.read_text(encoding='utf-8'))
    output = args.output_dir
    if output is not None:
        output.mkdir(parents=True, exist_ok=False)
    for name, build in (('frontend', frontend), ('backend', backend)):
        artifact = ('\n\n'.join(build(source)) + '\n').encode('utf-8')
        path = (output if output is not None else PUBLISHED) / (name + '.md')
        if output is None:
            if artifact != path.read_bytes():
                raise SystemExit(f'Frozen framework differs from generator: {path.name}')
        else:
            with path.open('xb') as stream:
                stream.write(artifact)
        print(f'{path.name}: {len(artifact)} bytes')


if __name__ == '__main__':
    main()
